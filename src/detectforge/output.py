"""Render alerts for humans (console), machines (JSON Lines) and ATT&CK Navigator."""

from __future__ import annotations

import json
from collections import Counter
from collections.abc import Sequence
from typing import Any, TextIO

from . import __version__
from .models import SEVERITIES, SEVERITY_RANK, Alert

_COLORS = {
    "critical": "\033[1;97;41m",
    "high": "\033[1;31m",
    "medium": "\033[33m",
    "low": "\033[36m",
    "informational": "\033[37m",
}
_DIM, _BOLD, _RESET = "\033[2m", "\033[1m", "\033[0m"


_CONTEXT_FIELDS = (("host", ("host", "name"), ("host", "hostname")), ("user", ("user", "name")))


def _fmt_time(alert_time: Any) -> str:
    return alert_time.strftime("%Y-%m-%d %H:%M:%SZ")


def _context(alert: Alert) -> list[str]:
    """Pull host/user from the triggering event so analysts see *where* it happened."""
    if not alert.evidence:
        return []
    last = alert.evidence[-1]
    found = []
    for label, *paths in _CONTEXT_FIELDS:
        for path in paths:
            node: Any = last
            for part in path:
                node = node.get(part) if isinstance(node, dict) else None
            if isinstance(node, (str, int)) and not any(label in k for k in alert.group):
                found.append(f"{label}={node}")
                break
    return found


def render_console(
    alerts: Sequence[Alert], stream: TextIO, color: bool, events_processed: int
) -> None:
    def paint(text: str, code: str) -> str:
        return f"{code}{text}{_RESET}" if color else text

    for alert in alerts:
        label = paint(f"[{alert.severity.upper()}]", _COLORS[alert.severity])
        stream.write(f"{label} {paint(alert.rule_id, _BOLD)}  {alert.title}\n")

        when = _fmt_time(alert.first_seen)
        if alert.last_seen != alert.first_seen:
            when += f" -> {_fmt_time(alert.last_seen)}"
        details = [when, f"events={alert.count}"]
        details += [f"{k}={v}" for k, v in alert.group.items()]
        details += _context(alert)
        stream.write(f"    {paint('  '.join(details), _DIM)}\n")

        if alert.techniques:
            attack = ", ".join(alert.techniques)
            if alert.tactics:
                attack += f"  ({', '.join(alert.tactics)})"
            stream.write(f"    ATT&CK: {attack}\n")
        stream.write("\n")

    by_severity = Counter(a.severity for a in alerts)
    rules_hit = len({a.rule_id for a in alerts})
    summary = (
        f"{len(alerts)} alert(s) from {rules_hit} rule(s) across {events_processed} event(s)"
    )
    stream.write(paint(summary, _BOLD) + "\n")
    if alerts:
        parts = [
            paint(f"{sev}: {by_severity[sev]}", _COLORS[sev])
            for sev in reversed(SEVERITIES)
            if by_severity[sev]
        ]
        stream.write("  " + "  ".join(parts) + "\n")


def write_jsonl(alerts: Sequence[Alert], stream: TextIO) -> None:
    for alert in alerts:
        stream.write(json.dumps(alert.to_dict(), default=str) + "\n")


def navigator_layer(alerts: Sequence[Alert], name: str = "detectforge findings") -> dict:
    """Build an ATT&CK Navigator layer: each observed technique is scored by alert count
    and coloured by the worst severity that hit it."""
    scores: Counter[str] = Counter()
    worst: dict[str, str] = {}
    rules: dict[str, set[str]] = {}
    for alert in alerts:
        for tid in alert.techniques:
            scores[tid] += 1
            rules.setdefault(tid, set()).add(alert.rule_id)
            if SEVERITY_RANK[alert.severity] > SEVERITY_RANK.get(worst.get(tid, ""), -1):
                worst[tid] = alert.severity
    palette = {
        "critical": "#b10026",
        "high": "#e31a1c",
        "medium": "#fd8d3c",
        "low": "#fecc5c",
        "informational": "#ffffb2",
    }
    return {
        "name": name,
        "versions": {"layer": "4.5", "navigator": "5.1.0", "attack": "16"},
        "domain": "enterprise-attack",
        "description": f"Generated by detectforge {__version__}",
        "techniques": [
            {
                "techniqueID": tid,
                "score": scores[tid],
                "color": palette[worst[tid]],
                "comment": f"{scores[tid]} alert(s); rules: {', '.join(sorted(rules[tid]))}",
                "enabled": True,
            }
            for tid in sorted(scores)
        ],
        "gradient": {"colors": ["#ffffff", "#e31a1c"], "minValue": 0,
                     "maxValue": max(scores.values(), default=1)},
        "legendItems": [{"label": sev, "color": palette[sev]} for sev in reversed(SEVERITIES)],
    }
